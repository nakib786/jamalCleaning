/**
 * Converts the theme's `cetro-icon` font into inline SVG path data.
 *
 * Reads the class -> codepoint map from the captured icons.css and the glyph
 * outlines from the captured woff2, and writes src/components/ui/icons.generated.ts
 * ({ name: { d, w } } in a 1000-unit em box, y already flipped for SVG).
 * Icons render as inline SVG, so no icon font is downloaded by visitors.
 */
import fs from "node:fs/promises";
import path from "node:path";
import * as fontkit from "fontkit";
import { CAPTURED_DIR, ROOT } from "../lib/site.ts";

const THEME = path.join(CAPTURED_DIR, "demo2.pavothemes.com/cetro/wp-content/themes/cetro/assets");

async function main(): Promise<void> {
  const css = await fs.readFile(path.join(THEME, "css/icons.css"), "utf8");
  const font = fontkit.create(
    await fs.readFile(path.join(THEME, "fonts/icons/cetro-icon-1.1.1.woff2")),
  ) as fontkit.Font;
  const scale = 1000 / font.unitsPerEm;
  const ascent = font.ascent * scale;

  const icons: Record<string, { d: string; w: number }> = {};
  for (const match of css.matchAll(/\.cetro-icon-([\w-]+):before\s*\{\s*content:\s*"(.+?)";/g)) {
    const [, name, content] = match;
    if (!name || !content) continue;
    const codePoint = content.startsWith("\\")
      ? Number.parseInt(content.slice(1), 16)
      : content.codePointAt(0);
    if (codePoint === undefined || Number.isNaN(codePoint)) continue;
    const glyph = font.glyphForCodePoint(codePoint);
    if (!glyph || glyph.id === 0) continue;
    // Font units are y-up; flip into SVG's y-down space and normalise to 1000 units.
    const d = glyph.path
      .scale(scale, -scale)
      .translate(0, ascent)
      .toSVG()
      .replace(/(\d+\.\d{2})\d+/g, "$1");
    if (d) icons[name] = { d, w: Math.round(glyph.advanceWidth * scale) };
  }

  const names = Object.keys(icons).sort();
  const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join("\n");
  const out = [
    "// Generated by tools/assets/extract-icons.ts from the Cetro theme icon font. Do not edit.",
    "// Paths use a 1000-unit em box (viewBox `0 0 w 1000`).",
    "export const ICONS = {",
    body,
    "} as const satisfies Record<string, { d: string; w: number }>;",
    "",
    "export type IconName = keyof typeof ICONS;",
    "",
  ].join("\n");
  const file = path.join(ROOT, "src/components/ui/icons.generated.ts");
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, out);
  console.log(
    `${names.length} icons -> ${path.relative(ROOT, file)} (ascent ${ascent.toFixed(0)}, upm ${font.unitsPerEm})`,
  );
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
